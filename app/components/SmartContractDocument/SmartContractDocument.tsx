/** Sub-component: recomputes the SHA-256 hash in the browser using Web Crypto API */
function LiveHashCheck({ pool, storedHash, sealedAt }: { pool: any; storedHash: string; sealedAt: string | Date }) {
  const [liveHash, setLiveHash] = useState<string | null>(null);
  const [checking, setChecking] = useState(false);

  const runCheck = async () => {
    setChecking(true);
    try {
      const { hashContractBrowser } = await import('@/lib/hashContract');
      const ts = typeof sealedAt === 'string' ? sealedAt : (sealedAt as Date).toISOString();
      const h = await hashContractBrowser(pool, ts);
      setLiveHash(h);
    } catch (e) {
      setLiveHash('ERROR_COMPUTING_HASH');
    } finally {
      setChecking(false);
    }
  };

  const verified = liveHash !== null && liveHash === storedHash;
  const tampered = liveHash !== null && liveHash !== storedHash;

  return (
    <div className="space-y-3">
      <div className="space-y-1">
        <p className="text-[10px] font-bold text-slate-400 uppercase">Re-computed Live Hash (Browser, now):</p>
        {liveHash ? (
          <div className={`border p-2.5 rounded-xl font-mono text-[10px] break-all transition-colors ${
            verified ? 'bg-emerald-50 border-emerald-200 text-emerald-700'
            : tampered ? 'bg-rose-50 border-rose-200 text-rose-700'
            : 'bg-slate-50 border-slate-200 text-slate-600'
          }`}>
            {liveHash}
          </div>
        ) : (
          <div className="bg-slate-50 border border-slate-200 p-2.5 rounded-xl text-[10px] text-slate-400 italic">
            Click &quot;Run Integrity Check&quot; to compute the live hash.
          </div>
        )}
      </div>

      <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-3 bg-slate-50 border border-slate-100 p-4 rounded-2xl">
        <div className="space-y-0.5">
          <p className="text-[10px] font-extrabold text-slate-400 uppercase">Authenticity Status:</p>
          {liveHash === null && (
            <p className="text-xs text-slate-500">Run the check to verify this document.</p>
          )}
          {verified && (
            <p className="text-xs font-bold text-emerald-700 flex items-center gap-1.5"> Verified  -  Document is intact since blockchain sealing</p>
          )}
          {tampered && (
            <p className="text-xs font-bold text-rose-700 flex items-center gap-1.5"> Tamper Alert  -  Document data has changed since sealing!</p>
          )}
        </div>
        <button
          onClick={runCheck}
          disabled={checking}
          className="px-4 py-2 text-xs font-bold rounded-xl bg-[#1A9B9A] hover:bg-[#147878] text-white transition-all disabled:opacity-50 flex items-center gap-1.5 whitespace-nowrap"
        >
          {checking ? <><span className="animate-spin inline-block">⟳</span> Computing…</> : ' Run Integrity Check'}
        </button>
      </div>
    </div>
  );
}

